/**
 * DANE PRZYKŁADOWE do prototypu – nie są to prawdziwe nabory.
 * Daty liczone względem dzisiejszego dnia, żeby oś czasu zawsze wyglądała realistycznie.
 */
function rel(days: number, base = new Date()): string {
  const d = new Date(base.getFullYear(), base.getMonth(), base.getDate() + days)
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`
}

